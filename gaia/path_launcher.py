"""Where the PATH launcher (``~/.local/bin/gaia``) may point, and moving it to the current plugin install."""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from pathlib import Path

LAUNCHER = "~/.local/bin/gaia"
GENERATED_MARK = "(generated by `gaia install`)"

# cmd.exe reads a batch file in the console code page and PowerShell 5.1 reads a
# BOM-less script as ANSI, so the .cmd keeps the locale codec and the .ps1 a BOM.
LAUNCHER_ENCODINGS = {".cmd": None, ".ps1": "utf-8-sig"}

_BAKED_BIN = re.compile(r'"([^"\r\n]+)[\\/]bin[\\/]gaia"')


def _plugins_dir() -> Path:
    return Path.home() / ".claude" / "plugins"


def _read_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def _key(path: Path) -> str:
    return os.path.normcase(str(Path(path).expanduser().resolve()))


def _under(path: Path, base: Path) -> bool:
    path_key, base_key = _key(path), _key(base)
    return path_key == base_key or path_key.startswith(base_key.rstrip(os.sep) + os.sep)


def plugin_key(root: Path) -> str | None:
    """``gaia@<marketplace>`` when *root* is a version folder of Claude Code's plugin cache, else None."""
    root = Path(root)
    if len(root.parents) < 3 or root.parent.name != "gaia" or _key(root.parents[2]) != _key(_plugins_dir() / "cache"):
        return None
    return f"gaia@{root.parents[1].name}"


def _directory_marketplace(key: str) -> bool:
    known = _read_json(_plugins_dir() / "known_marketplaces.json").get(key.partition("@")[2])
    source = known.get("source") if isinstance(known, dict) else None
    return isinstance(source, dict) and source.get("source") == "directory"


def recorded_installs(key: str) -> list[Path]:
    """Every installPath Claude Code's installed_plugins.json records for *key*, in its order."""
    entries = (_read_json(_plugins_dir() / "installed_plugins.json").get("plugins") or {}).get(key)
    return [Path(entry["installPath"]) for entry in (entries if isinstance(entries, list) else [])
            if isinstance(entry, dict) and isinstance(entry.get("installPath"), str)]


def stale_install(package: Path) -> list[Path] | None:
    """The recorded installs on disk to run instead of *package* (maybe none), or None unless *package* is an unrecorded marketplace version."""
    key = plugin_key(package)
    if key is None or _directory_marketplace(key):
        return None
    recorded = recorded_installs(key)
    if any(_key(path) == _key(package) for path in recorded):
        return None
    return [path for path in recorded if path.is_dir()]


def _ephemeral(path: Path) -> bool:
    path = Path(path).expanduser()
    if ".project-worktrees" in path.parts or (path / ".git").exists():
        return True
    from gaia.paths.resolver import data_dir

    bases = (Path(tempfile.gettempdir()), Path("/tmp"), data_dir(), Path.home() / ".gaia")
    if any(_under(path, base) for base in bases):
        return True
    key = plugin_key(path)
    return key is not None and _directory_marketplace(key)


def refusal(root: Path, link: Path) -> str | None:
    """Why a launcher at *link* must not run the Gaia at *root*: a temporary or dev copy serves only an equally temporary home."""
    if _ephemeral(root) and not _ephemeral(Path(link).expanduser().parent):
        return (f"refusing to point {link} at {root}: a temporary, scratch, worktree, source-checkout "
                "or dev-plugin copy; run `gaia install --path` from an installed Gaia")
    return None


def launcher_files(link: Path) -> list[Path]:
    """The files the launcher at *link* is made of on this platform."""
    if sys.platform == "win32":
        return [link.with_suffix(suffix) for suffix in LAUNCHER_ENCODINGS]
    return [link]


def is_generated(path: Path) -> bool:
    """True when *path* is a Windows launcher some `gaia install` wrote."""
    try:
        return GENERATED_MARK in path.read_text(encoding=LAUNCHER_ENCODINGS.get(path.suffix), errors="replace")
    except OSError:
        return False


def _replaceable(old_root: Path, root: Path, recorded: list[Path]) -> bool:
    return (_key(old_root.parent) == _key(root.parent) and _key(old_root) != _key(root)
            and all(_key(path) != _key(old_root) for path in recorded))


def refresh_launcher(root: Path, link: Path | str = LAUNCHER) -> list[Path]:
    """Rewrite an existing launcher that runs an unrecorded sibling version of recorded *root* to run *root*; returns the files rewritten."""
    root, link = Path(root), Path(link).expanduser()
    key = plugin_key(root)
    if key is None or _directory_marketplace(key) or refusal(root, link):
        return []
    recorded = recorded_installs(key)
    if all(_key(path) != _key(root) for path in recorded):
        return []
    entry = root / "bin" / "gaia"
    rewritten = []
    for path in launcher_files(link):
        if path.is_symlink():
            target = Path(os.readlink(path))
            if _replaceable((path.parent / target).parent.parent, root, recorded):
                path.unlink()
                path.symlink_to(entry)
                rewritten.append(path)
        elif path.is_file() and is_generated(path):
            encoding = LAUNCHER_ENCODINGS.get(path.suffix)
            try:
                text = path.read_text(encoding=encoding)
            except UnicodeDecodeError:
                continue
            baked = _BAKED_BIN.search(text)
            if baked and _replaceable(Path(baked.group(1)), root, recorded):
                path.write_text(text.replace(baked.group(0), f'"{entry}"', 1), encoding=encoding)
                rewritten.append(path)
    return rewritten
