def register(subparsers):
    """Register the 'uninstall' subcommand."""
    p = subparsers.add_parser(
        "uninstall",
        help="Revert exactly what Gaia (install or plugin) wrote here (the DB is never touched)",
        description=(
            "Revert the workspace's install manifest: every file, link and\n"
            "settings key `gaia install` or a plugin session wrote returns to its\n"
            "prior state, and the --path launcher / Windows setx it recorded are\n"
            "taken back. Files Gaia did not create are never removed. A workspace\n"
            "wired before manifests existed (a plugin one included) is adopted\n"
            "and reverted the same way.\n"
            "\n"
            "It also removes what a package manager or `gaia dev` left: the Gaia\n"
            "package under node_modules and its .bin shim, Gaia's line in\n"
            "package.json and package-lock.json (your other dependencies stay),\n"
            "the packed tarballs `gaia dev` cached, and hook scratch state. What it\n"
            "cannot fix itself (a pnpm-lock.yaml or yarn.lock, .claude/logs) is\n"
            "listed as left in place, with the reason. --dry-run lists exactly what\n"
            "the real run does.\n"
            "\n"
            "The user DB at ~/.gaia/gaia.db is NEVER modified or deleted. A gzip\n"
            "snapshot of it is written by default; --no-backup skips it.\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--preuninstall",
        action="store_true",
        default=False,
        help="Adapt output for npm preuninstall hook (still exits 0)",
    )
    p.add_argument(
        "--workspace",
        type=str,
        default=None,
        help="Workspace path to clean (default: auto-detect via .claude/)",
    )
    p.add_argument(
        "--channel",
        choices=("npm", "plugin", "opencode"),
        default=None,
        help=(
            "Take back only what this channel wrote and keep the other channels "
            "recorded in the workspace (default: every channel)"
        ),
    )
    p.add_argument(
        "--dry-run",
        dest="dry_run",
        action="store_true",
        default=False,
        help="Print actions without modifying anything",
    )
    p.add_argument(
        "--quiet",
        action="store_true",
        default=False,
        help="Suppress non-error output",
    )
    p.add_argument(
        "--json",
        action="store_true",
        default=False,
        help="Output results as JSON",
    )
    p.add_argument(
        "--db-path",
        type=str,
        default=None,
        help=f"Override DB path (default: {DEFAULT_DB_PATH})",
    )
    p.add_argument(
        "--no-backup",
        dest="no_backup",
        action="store_true",
        default=False,
        help=(
            "Skip the gzip snapshot of ~/.gaia/gaia.db that uninstall "
            "writes by default (the DB is preserved in place either way)"
        ),
    )
    p.add_argument(
        "--snapshot-dir",
        dest="snapshot_dir",
        type=str,
        default=None,
        help=(
            f"Directory for the default snapshot "
            f"(default: {DEFAULT_SNAPSHOT_DIR}). Ignored with --no-backup."
        ),
    )
    return p


def cmd_uninstall(args: argparse.Namespace) -> int:
    """Execute the uninstall subcommand: 0 from the cleanup path, 1 for a --channel the workspace does not record.

    The DB at ``db_path`` is NEVER deleted by this function -- no flag,
    combination of flags, or branch below removes it. The default gzip
    snapshot (skippable via --no-backup) only ever writes an additional
    file alongside the live DB.
    """
    dry_run = bool(getattr(args, "dry_run", False))
    backup = not bool(getattr(args, "no_backup", False))
    preuninstall = bool(getattr(args, "preuninstall", False))
    quiet = bool(getattr(args, "quiet", False))
    as_json = bool(getattr(args, "json", False))
    db_override = getattr(args, "db_path", None)

    workspace = _resolve_workspace(getattr(args, "workspace", None))
    db_path = Path(db_override).expanduser() if db_override else DEFAULT_DB_PATH

    snapshot_override = getattr(args, "snapshot_dir", None)
    snapshot_dir = (
        Path(snapshot_override).expanduser() if snapshot_override else DEFAULT_SNAPSHOT_DIR
    )

    result: dict = {
        "mode": "preuninstall" if preuninstall else "manual",
        "workspace": str(workspace),
        "db_path": str(db_path),
        "dry_run": dry_run,
        "backup_requested": backup,
    }

    try:
        result["manifest"] = _manifest.uninstall(
            workspace, dry_run=dry_run, package_manager_owns_package=preuninstall,
            channel=getattr(args, "channel", None),
        )
    except _manifest.ChannelNotRecorded as exc:
        print(f"gaia uninstall: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # noqa: BLE001
        result["cleanup_error"] = str(exc)

    # --- DB handling --------------------------------------------------------
    # The DB is ALWAYS preserved -- uninstall has no delete path for it.
    # A gzip snapshot is taken by DEFAULT (skippable via --no-backup): it is
    # purely additive -- writes a new snapshot and rotates old ones, never
    # touches the source DB, so a failed backup never blocks anything.
    if backup:
        snapshot_result = _snapshot_db(db_path, snapshot_dir, dry_run)
        result["snapshot"] = snapshot_result

        if not quiet and not as_json:
            if snapshot_result.get("created"):
                print(f"  Backup created: {snapshot_result['path']}")
            elif dry_run and db_path.exists():
                print(f"  Would create backup: {snapshot_result['path']}")
            elif "error" in snapshot_result:
                print(
                    f"  WARNING: backup failed ({snapshot_result['error']}); "
                    f"DB was NOT touched.",
                    file=sys.stderr,
                )

    result["db"] = {
        "path": str(db_path),
        "found": db_path.exists(),
        "preserved": True,
        "note": "gaia uninstall never deletes the DB. It is snapshotted by default (use --no-backup to skip).",
    }

    # --- Reporting --------------------------------------------------------
    if as_json:
        print(json.dumps(result, indent=2))
    elif not quiet:
        _print_human(result, preuninstall=preuninstall, dry_run=dry_run)

    # The cleanup path exits 0 so npm uninstall continues even on partial failures.
    return 0


def _print_human(result: dict, *, preuninstall: bool, dry_run: bool) -> None:
    """Print a human-friendly summary."""
    header = "gaia uninstall (preuninstall)" if preuninstall else "gaia uninstall"
    print(f"\n{header}")
    if dry_run:
        print("  (dry-run -- no files will be modified)")
    print(f"  workspace: {result['workspace']}")
    print(f"  db:        {result['db_path']}")
    print()

    manifest = result.get("manifest") or {}
    db = result.get("db") or {}

    source = manifest.get("source", "none")
    if source == "none":
        print("  Nothing to revert: no Gaia install recorded in this workspace.")
    elif source == "adopted":
        print("  No manifest: reverting the footprint of an install that predates it.")
    if manifest.get("remaining"):
        print(f"  Channel {manifest['channel']} only; {', '.join(manifest['remaining'])} stays recorded.")
    verb = "Would restore" if dry_run else "Restored"
    for rel in manifest.get("reverted", []):
        print(f"  {verb}: {rel}")
    for name in manifest.get("env", []):
        print(f"  {verb}: user environment variable {name}")
    removed, edited = ("Would remove", "Would edit") if dry_run else ("Removed", "Edited")
    for item in manifest.get("artifacts", []):
        print(f"  {removed if item['action'] == 'remove' else edited}: {item['path']}  ({item['reason']})")
    for item in manifest.get("kept", []):
        print(f"  Left in place: {item['path']}  ({item['reason']})")

    print()
    snapshot = result.get("snapshot") or {}
    if snapshot:
        if snapshot.get("created"):
            print(f"  Backup written: {snapshot.get('path')}")
        elif "error" in snapshot:
            print(f"  Backup failed: {snapshot.get('error')}")
    if db.get("found"):
        print(f"  DB preserved: {db.get('path')}")
        if not result.get("backup_requested"):
            print("    (--no-backup: snapshot skipped; uninstall never deletes the DB)")
    else:
        print(f"  DB not present: {db.get('path')}")

    print()
    if "cleanup_error" in result:
        print(f"  Warning: cleanup error: {result['cleanup_error']}")
        print()
    if preuninstall:
        print("  Continuing with npm uninstall...")
    else:
        print("  Done.")
    print()
